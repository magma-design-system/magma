import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { collectFiles, routeFile, runMigration } from './index.js';
import { JUMPS } from './manifest/manifests.js';

describe('routeFile', () => {
  it('routes by extension in auto mode', () => {
    expect(routeFile('a.css', 'auto')?.surface).toBe('css');
    expect(routeFile('a.scss', 'auto')?.surface).toBe('css');
    expect(routeFile('a.tsx', 'auto')?.surface).toBe('react');
    // JSX in .js, and the strings of a Tailwind 3 config (category N reports them)
    expect(routeFile('tailwind.config.js', 'auto')?.surface).toBe('react');
    expect(routeFile('a.mjs', 'auto')?.surface).toBe('react');
    expect(routeFile('a.ts', 'auto')?.surface).toBe('angular'); // inline templates
    expect(routeFile('a.html', 'auto')?.surface).toBe('html');
    expect(routeFile('a.md', 'auto')).toBeNull();
  });

  it('forces the surface when a framework is given', () => {
    expect(routeFile('a.html', 'angular')?.surface).toBe('angular');
    expect(routeFile('a.ts', 'angular')?.surface).toBe('angular');
    expect(routeFile('a.html', 'html')?.surface).toBe('html');
  });
});

describe('runMigration (dry-run over a temp tree)', () => {
  const dir = mkdtempSync(join(tmpdir(), 'magma-codemods-'));

  beforeAll(() => {
    mkdirSync(join(dir, 'node_modules', 'pkg'), { recursive: true });
    writeFileSync(join(dir, 'page.html'), '<mds-button tone="ghost">Save</mds-button>');
    writeFileSync(join(dir, 'theme.css'), '.a { --mds-banner-gap: 8px; }');
    writeFileSync(join(dir, 'node_modules', 'pkg', 'skip.html'), '<mds-button>nope</mds-button>');
  });

  it('scans relevant files, ignores node_modules, and does not write in dry-run', async () => {
    const { report } = await runMigration({ paths: [dir], framework: 'auto', from: 1 });
    expect(report.dryRun).toBe(true);
    expect(report.summary.filesChanged).toBe(2); // page.html + theme.css
    // node_modules content is ignored
    expect(report.files.every((f) => !f.file.includes('node_modules'))).toBe(true);
    // dry-run leaves files on disk untouched
    expect(readFileSync(join(dir, 'page.html'), 'utf8')).toBe(
      '<mds-button tone="ghost">Save</mds-button>',
    );
  });

  it('writes a JSON report when requested', async () => {
    const reportPath = join(dir, 'report.json');
    await runMigration({ paths: [dir], framework: 'auto', from: 1, reportPath });
    const json = JSON.parse(readFileSync(reportPath, 'utf8'));
    expect(json.summary.filesChanged).toBeGreaterThanOrEqual(2);
  });

  it('applies changes with write: true', async () => {
    const wdir = mkdtempSync(join(tmpdir(), 'magma-codemods-w-'));
    writeFileSync(join(wdir, 'page.html'), '<mds-button>Save</mds-button>');
    await runMigration({ paths: [wdir], framework: 'auto', from: 1, write: true, force: true });
    expect(readFileSync(join(wdir, 'page.html'), 'utf8')).toBe(
      '<mds-button label="Save"></mds-button>',
    );
  });

  it('collectFiles takes a directory literally, glob characters included', async () => {
    const root = mkdtempSync(join(tmpdir(), 'magma-codemod-glob-'));
    const nested = join(root, 'app', '(pages)', '[id]');
    mkdirSync(nested, { recursive: true });
    writeFileSync(join(nested, 'view.tsx'), 'export {};');
    for (const p of [join(root, 'app', '(pages)'), nested])
      expect(await collectFiles([p], root, [])).toEqual([join(nested, 'view.tsx')]);
  });

  it('collectFiles expands directories and honours ignore', async () => {
    const files = await collectFiles([dir], dir, []);
    expect(files.some((f) => f.endsWith('page.html'))).toBe(true);
    expect(files.some((f) => f.includes('node_modules'))).toBe(false);
  });
});

describe('runMigration: the jumps', () => {
  it('reports a file the design-tokens CLI generated instead of migrating it', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'magma-codemods-generated-'));
    const banner =
      '/*\n@magma-design-system/design-tokens v15.3.0\nGenerated by Style Dictionary\nDo not edit directly\n*/\n';
    writeFileSync(
      join(dir, 'colors-rgb-theme.css'),
      `${banner}:root { --magma-accent-fg: 0 85 204; }\n`,
    );
    const { report } = await runMigration({ paths: [dir], framework: 'auto' });
    const file = report.files[0]!;
    expect(file.changed).toBe(false);
    expect(file.findings).toHaveLength(1);
    expect(file.findings[0]!.message).toContain('regenerate it with the design-tokens of Magma 3');
  });

  const v1Button = '<mds-button tone="ghost">Save</mds-button>';
  const v2Sheet = '.a { background: rgb(var(--magma-surface-raised) / 0.5); }';

  it('migrates v2 -> v3 by default, and never runs the v1 -> v2 rules', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'magma-codemods-v3-'));
    writeFileSync(join(dir, 'page.html'), v1Button);
    writeFileSync(join(dir, 'theme.css'), v2Sheet);
    const { report } = await runMigration({ paths: [dir], framework: 'auto' });
    expect([report.fromVersion, report.toVersion]).toEqual(['2', '3']);
    expect(report.jumps).toEqual(['2 -> 3']);
    // the v1 markup is not touched: tone and the slot are v1 -> v2 rules
    expect(report.files.find((f) => f.file.endsWith('page.html'))?.changed).toBe(false);
    const css = report.files.find((f) => f.file.endsWith('theme.css'))!;
    expect(css.diff).toContain(
      '+.a { background: color-mix(in srgb, var(--magma-surface-raised) 50%, transparent); }',
    );
    expect(css.findings.every((f) => f.jump === '2 -> 3')).toBe(true);
  });

  it('with from: 1 runs both jumps, the second on what the first wrote, in one diff', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'magma-codemods-chain-'));
    // v1 names the seed `--tone-neutral` (v2 renames it `-seed`), read as channels
    writeFileSync(join(dir, 'theme.css'), '.a { color: rgb(var(--tone-neutral)); }');
    const { report } = await runMigration({ paths: [dir], framework: 'auto', from: 1 });
    expect(report.jumps).toEqual(['1.12.0 -> 2.0.0', '2 -> 3']);
    const file = report.files[0]!;
    expect(file.diff).toContain('+.a { color: var(--tone-neutral-seed); }');
    expect(file.diff?.match(/^@@/gm)).toHaveLength(1);
    const jumps = file.findings.filter((f) => f.kind === 'change').map((f) => f.jump);
    expect(jumps).toEqual(['1.12.0 -> 2.0.0', '2 -> 3']);
  });

  it('drops the v1 -> v2 channel flag that the v2 -> v3 rename makes moot', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'magma-codemods-moot-'));
    writeFileSync(join(dir, 'theme.css'), '.a { --mds-input-variant-color: #ff0000; }');
    const chain = await runMigration({ paths: [dir], framework: 'auto', from: 1 });
    const file = chain.report.files[0]!;
    // v1 hex -> v2 `-rgb` (channels) -> v3 colour again: the hex is right as it is
    expect(file.diff).toBeUndefined();
    expect(file.findings.some((f) => f.kind === 'flag')).toBe(false);
    // a run that stops at v2 (one manifest, the override) still asks for the conversion
    const manifestPath = join(dir, 'v1-to-v2.json');
    writeFileSync(manifestPath, JSON.stringify(JUMPS[1]));
    const v2Only = await runMigration({
      paths: [join(dir, 'theme.css')],
      framework: 'auto',
      manifestPath,
    });
    expect(v2Only.report.jumps).toEqual(['1.12.0 -> 2.0.0']);
    expect(v2Only.report.files[0]!.findings.some((f) => f.kind === 'flag')).toBe(true);
  });
});
