/**
 * Build the list of custom properties Magma publishes as colours, which the
 * v2 -> v3 colour rule (category N, #918) rewrites: a read `rgb(var(--x))` and a
 * definition `--x: r g b` are migrated only when `--x` is on this list, so a
 * product's own triplet variable is left as it is.
 *
 *   npx nx run codemod:generate.colors
 *   # = tsx scripts/build-color-tokens.ts [out.ts]
 *
 * Source (build them first: design-tokens -> styles): the DTCG sets of the two
 * packages, `projects/design-tokens/dist/dtcg/*.tokens.json` and
 * `projects/styles/dist/dtcg/*.tokens.json`; what counts as a colour is written
 * in `src/manifest/color-token-source.ts`. A colour token with no custom
 * property breaks the contract and fails the build instead of being skipped.
 *
 * The names are the same in Magma 2 and Magma 3, so the list can be built from
 * either. The output is committed (`src/manifest/color-tokens.generated.ts`),
 * so the codemod has no runtime dependency on the two packages; a test fails
 * when it differs from the built sets.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { collectColorTokens } from '../src/manifest/color-token-source.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJECTS = join(HERE, '..', '..');
const outPath = process.argv[2] ?? join(HERE, '..', 'src', 'manifest', 'color-tokens.generated.ts');
const SOURCES = [
  join(PROJECTS, 'design-tokens', 'dist', 'dtcg'),
  join(PROJECTS, 'styles', 'dist', 'dtcg'),
];

const files: Record<string, unknown> = {};
for (const dir of SOURCES) {
  if (!existsSync(dir)) {
    console.error(`${dir} is missing: build design-tokens and styles first`);
    process.exit(2);
  }
  for (const name of readdirSync(dir)
    .filter((f) => f.endsWith('.tokens.json'))
    .sort())
    files[join(dir, name)] = JSON.parse(readFileSync(join(dir, name), 'utf8'));
}
const { names, missing } = collectColorTokens(files);
if (missing.length > 0) {
  console.error(`colour tokens with no custom property:\n  ${missing.join('\n  ')}`);
  process.exit(2);
}

const lines = [
  '/* AUTO-GENERATED by scripts/build-color-tokens.ts - do not edit by hand.',
  ' * Regenerate with `npx nx run codemod:generate.colors` after a tokens change. */',
  '',
  '/** Every custom property (without `--`) the design-tokens and styles DTCG sets type as a colour. */',
  `export const colorTokenNames: readonly string[] = ${JSON.stringify(names)};`,
  '',
];
const prettierConfig = await resolveConfig(outPath);
writeFileSync(outPath, await format(lines.join('\n'), { ...prettierConfig, filepath: outPath }));
console.log(
  `${names.length} colour custom properties from ${Object.keys(files).length} DTCG files -> ${outPath}`,
);
