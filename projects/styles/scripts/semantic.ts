import chalk from 'chalk';
import { mkdir, readFile, readdir, writeFile } from 'fs/promises';
import { join, resolve } from 'path';
import { BUILD_DIR, PROJECT_DIR } from './meta';
import { lookupFromCss, resolve as resolveValue, type Tokens } from './css-resolve';
import {
  cssDecl,
  scaleFamily,
  scaleStepList,
  type SemanticDecl,
} from '../../design-tokens/semantic.config';
import { semanticModel } from '../../design-tokens/semantic.model';

/**
 * Generate the semantic color layer (A9) from design-tokens/semantic.config.ts:
 *  - build/css/semantic.css        the `--magma-*` layer components consume
 *  - build/tailwind/semantic.css   the Tailwind `@theme` bridge (--color-* re-exports)
 *  - build/css/themes.css          named-theme overrides (data-theme-name, spec 8)
 *
 * All are GENERATED and gitignored; they are staged under build/ (out of the
 * hand-authored source dirs) and the copy step ships them to dist. The
 * tracked contract is design-tokens/semantic.config.ts, expanded into declarations
 * by design-tokens/semantic.model.ts, which also feeds the DTCG export of
 * design-tokens: this script only prints them as CSS.
 */

const model = semanticModel();
const { tint, contrastLevel } = model;

const HEADER = (what: string) =>
  `/*\n  ${what}\n  GENERATED by scripts/semantic.ts from semantic.config.ts - do NOT edit by hand.\n` +
  `  Contract + rationale: semantic.config.ts and SEMANTIC_COLOR_SPEC.md.\n*/\n`;

/** A declaration, preceded by its note when it has one. */
const printDecl = (decl: SemanticDecl): string[] => [
  ...(decl.note ? [`  /* ${decl.note} */`] : []),
  cssDecl(decl),
];

const layer: string[] = ['', ':root {'];
model.base.forEach(({ title, decls }, index) => {
  if (index) layer.push('');
  layer.push(`  /* ${title} */`, ...decls.flatMap(printDecl));
});
layer.push('}', '');

// Same selectors as the global dark layer (the design-tokens css-vars-rgb
// template), so the ink flips exactly when the primitives do.
if (model.dark.length) {
  const rules = model.dark.map(cssDecl);
  layer.push(
    '/* Dark: the fill ink takes the canvas (spec 6.5), the shadow ink pure black (spec 6.1c) */',
    ':root:not(.pref-theme-scheme-light).pref-mode-dark,',
    ':root.pref-theme-scheme-dark {',
    ...rules,
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not(.pref-theme-scheme-light).pref-mode-system,',
    '  :root:not([data-magma-pref]) {',
    ...rules.map((rule) => `  ${rule}`),
    '  }',
    '}',
    '',
  );
}

// The Tailwind bridge re-exports every public role, in the order the layer declares them.
const bridge = model.base.flatMap(({ decls }) => decls).filter((decl) => decl.tw);

/**
 * Each role of the bridge carries its light default as the fallback of its `var()`.
 * Tailwind IntelliSense resolves the colour of a utility from `@theme` and from literal
 * `var()` fallbacks only, never from the `:root` of semantic.css: without a literal the
 * 111 semantic utilities came with no swatch, while the palette ones, which carry a
 * fallback, had theirs. The value is the default (light) one, as every fallback in Magma,
 * never the dark one; so a page without semantic.css paints a role in its light default.
 */
const bridgeCss = (lookup: Tokens): string => {
  const unresolved: string[] = [];
  const body = bridge.map(({ name, tw }) => {
    const triplet = resolveValue(`var(--${name})`, lookup, '0.0025rem').replace(/\s+/g, ' ').trim();
    if (!/^\d{1,3} \d{1,3} \d{1,3}$/.test(triplet)) unresolved.push(`--${name} -> ${triplet}`);
    return `  --color-${tw}: rgb(var(--${name}, ${triplet}));`;
  });
  if (unresolved.length) {
    throw new Error(
      `${unresolved.length} semantic role(s) do not resolve to an rgb triplet for the bridge fallback:\n` +
        unresolved.map((u) => `  ${u}`).join('\n'),
    );
  }
  return `${HEADER('Tailwind bridge for the semantic color layer.')}\n@theme {\n${body.join('\n')}\n}\n`;
};

// Two selectors per scope, the same shape the global dark layer uses (see the
// design-tokens css-vars-rgb template) and the per-component `*-pref-contrast.css`
// sheets: the explicit `pref-contrast-more` class published by mds-pref-contrast,
// then an @media block covering `pref-contrast-system` and a page with no mds-pref
// controller at all. An explicit `pref-contrast-no-preference` matches neither, so
// opting out keeps the base steps.
/**
 * The contrast blocks for one scope. `scope` is an extra `:root` qualifier (empty
 * for the base layer, `[data-theme-name='x']` for a named theme). Empty string when
 * nothing is promoted.
 */
const contrastBlocks = (scope: string, decls: SemanticDecl[]): string => {
  const rules = decls.map(cssDecl);
  if (!rules.length) return '';
  return [
    `:root${scope}.pref-contrast-${contrastLevel} {`,
    rules.join('\n'),
    '}',
    '',
    `@media (prefers-contrast: ${contrastLevel}) {`,
    `  :root${scope}.pref-contrast-system,`,
    `  :root${scope}:not([data-magma-pref]) {`,
    rules.map((rule) => `  ${rule}`).join('\n'),
    '  }',
    '}',
  ].join('\n');
};

const contrastCss = contrastBlocks('', model.contrast);
const contrastComment =
  '/* Contrast (spec 9.3): pref-contrast-more promotes text + border to stronger same-family steps (tint block and every hue) and the page surface to the paper of the mode. */';
const layerCss =
  `${HEADER('Semantic color layer (--magma-*) - the contract components consume.')}${layer.join('\n')}` +
  (contrastCss ? `\n${contrastComment}\n${contrastCss}\n` : '');

// Named themes (spec 8): one override block per theme, then its own contrast
// blocks. A theme that changes nothing (the base tint, no accent override) emits
// nothing.
const themeBlocks = model.themes
  .map(({ name, decls, contrast }) => {
    const scope = `[data-theme-name='${name}']`;
    const block = decls.length ? `:root${scope} {\n${decls.map(cssDecl).join('\n')}\n}` : '';
    return [block, contrastBlocks(scope, contrast)].filter(Boolean).join('\n\n');
  })
  .filter(Boolean);
const themesCss = `${HEADER('Named themes - retint the --magma-tint-* block per data-theme-name (spec 8).')}\n${themeBlocks.join('\n\n')}\n`;

/** Every ramp family a theme points at, so they can be checked against the tokens. */
const rampFamilies = new Map<string, string>([
  ['(base tint)', scaleFamily(tint)],
  ...model.themes
    .filter(({ ramp }) => ramp)
    .map(({ name, ramp }): [string, string] => [name, ramp as string]),
]);

/**
 * A theme is only eligible if its family ships a full ramp, not just a surface.
 * Surfaces can be opted in per group, so a family can have `--surface-x-*` and no
 * `--x-01..10` - and a ramp pointer that resolves to nothing would silently put
 * the wash band, the shadow ink, the inverse pair and the neutral hue back on
 * whatever the fallback chain finds. The
 * step list is checked against the emitted primitives rather than assumed.
 */
/** The stylesheets of design-tokens/dist/css, where the primitives the roles point at live. */
const tokenSheets = async (): Promise<{ css: string; from: string }[]> => {
  const tokensDir = resolve(PROJECT_DIR, '../design-tokens/dist/css');
  const files = (await readdir(tokensDir)).filter((f) => f.endsWith('.css'));
  return Promise.all(
    files.map(async (file) => ({
      css: await readFile(resolve(tokensDir, file), 'utf8'),
      from: file,
    })),
  );
};

const assertRampsExist = async (sheets: { css: string }[]): Promise<void> => {
  const declared = new Set<string>();
  for (const { css } of sheets)
    for (const match of css.matchAll(/^\s*(--[a-z0-9-]+)\s*:/gim)) declared.add(match[1]);

  const missing: string[] = [];
  for (const [theme, family] of rampFamilies)
    for (const step of scaleStepList())
      if (!declared.has(`--${family}-${step}`)) missing.push(`${theme} -> --${family}-${step}`);

  if (missing.length) {
    throw new Error(
      `${missing.length} --magma-tint-scale-* pointer(s) have no primitive to resolve to:\n` +
        missing.map((m) => `  ${m}`).join('\n') +
        `\nA theme needs BOTH a surface and a full ramp. Either opt the family's group` +
        ` into the ramp, or name the ramp explicitly in semantic.config.ts themes,` +
        ` e.g. { surface: 'blue', scale: 'label-blue' }.`,
    );
  }
};

async function main() {
  const sheets = await tokenSheets();
  await assertRampsExist(sheets);
  // the light default of every role: the primitives, then the layer just generated
  const lookup = lookupFromCss([...sheets, { css: layerCss, from: 'semantic.css' }]);
  const cssDir = join(BUILD_DIR, 'css');
  const tailwindDir = join(BUILD_DIR, 'tailwind');
  await mkdir(cssDir, { recursive: true });
  await mkdir(tailwindDir, { recursive: true });
  await writeFile(join(cssDir, 'semantic.css'), layerCss, 'utf8');
  await writeFile(join(tailwindDir, 'semantic.css'), bridgeCss(lookup), 'utf8');
  await writeFile(join(cssDir, 'themes.css'), themesCss, 'utf8');
  console.info(
    chalk.green(
      `Generated semantic layer: ${bridge.length} tokens + ${themeBlocks.length} named themes ` +
        `+ ${model.contrast.length} pref-contrast-more promotions ` +
        `(build/css/semantic.css + build/tailwind/semantic.css + build/css/themes.css).`,
    ),
  );
}

main().catch((error) => {
  console.error(chalk.red(error instanceof Error ? (error.stack ?? error.message) : String(error)));
  process.exitCode = 1;
});
