import chalk from 'chalk';
import { mkdir, writeFile } from 'fs/promises';
import { join } from 'path';
import { BUILD_DIR } from './meta';
import { darkScheme } from '../../design-tokens/src/formats/dark-scheme';

/**
 * Generate the Tailwind `dark:` variant (#1100): build/tailwind/dark-mode.css, imported by
 * tailwind/theme.css and shipped next to it by the copy step.
 *
 * Without it Tailwind compiles `dark:` on `@media (prefers-color-scheme: dark)`, the OS
 * only: a page in `pref-mode-dark` on a light OS never got its `dark:` rules. The variant
 * matches where the palette turns dark, the selectors of the design-tokens darkScheme, so a
 * `dark:` rule flips exactly when the roles do, `system` and the theme scheme included.
 *
 * Each selector matches the root and everything under it, the form of Tailwind's own class
 * variant, inside `:where()` so a `dark:` utility keeps the weight of a plain one. Light DOM
 * only: in a shadow root `:root` matches nothing, so a component refines the mode in its
 * `*-pref-mode.css` sheet instead.
 */

// one line: Tailwind keeps the whitespace of the list in the selectors it compiles
const where = (selectors: readonly string[], indent: string): string =>
  [
    `${indent}&:where(${selectors.flatMap((selector) => [selector, `${selector} *`]).join(', ')}) {`,
    `${indent}  @slot;`,
    `${indent}}`,
  ].join('\n');

const variantCss = [
  '/*',
  '  Tailwind `dark:` variant on the Magma mode.',
  '  GENERATED by scripts/dark-variant.ts from the design-tokens darkScheme - do NOT edit by hand.',
  '*/',
  '',
  '@custom-variant dark {',
  where(darkScheme.forced, '  '),
  '',
  `  @media ${darkScheme.media} {`,
  where(darkScheme.system, '    '),
  '  }',
  '}',
  '',
].join('\n');

async function main() {
  const tailwindDir = join(BUILD_DIR, 'tailwind');
  await mkdir(tailwindDir, { recursive: true });
  await writeFile(join(tailwindDir, 'dark-mode.css'), variantCss, 'utf8');
  console.info(chalk.green('Generated the dark: variant (build/tailwind/dark-mode.css).'));
}

main().catch((error) => {
  console.error(chalk.red(error instanceof Error ? (error.stack ?? error.message) : String(error)));
  process.exitCode = 1;
});
